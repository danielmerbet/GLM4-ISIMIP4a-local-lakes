#!/bin/bash
# Writes bin/glm-run: a launcher for bin/glm-built that sets LD_LIBRARY_PATH to exactly the
# library directories the binary resolves to under its BUILD environment.
#
#   bash make_glm_launcher.sh        # run after build_glm4.sh, on each machine
#
# Why: on Hydra the calibration runs GLM from inside R, and R's module (R/4.5.1-gfbf-2025a,
# GCC 14.2 / netCDF 4.9.3) cannot be loaded together with GLM's build modules
# (GCC/13.3.0 + netCDF/4.9.2-gompi-2024a). Under R's modules libnetcdf.so.19 is not found.
# Loading modules inside every run would cost ~1 s x thousands of runs; pinning the
# directories costs nothing and keeps the binary and its libraries identical to the build.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
if command -v module >/dev/null 2>&1 && [ -n "${VSC_INSTITUTE:-}" ]; then
  module purge
  module load GCC/13.3.0 netCDF/4.9.2-gompi-2024a      # same as build_glm4.sh
fi
missing=$(ldd "$HERE/bin/glm-built" | grep "not found" || true)
[ -z "$missing" ] || { echo "unresolved libraries under build environment:"; echo "$missing"; exit 1; }
dirs=$(ldd "$HERE/bin/glm-built" | awk '/=> \//{print $3}' | xargs -n1 dirname | sort -u | tr '\n' ':' | sed 's/:$//')
# Written to a temporary file and renamed: running jobs call bin/glm-run for every model run
# and must never see a half-written launcher.
cat > "$HERE/bin/glm-run.new" <<EOF
#!/bin/bash
# generated by make_glm_launcher.sh on $(hostname) $(date -u +%FT%TZ)
export LD_LIBRARY_PATH="$dirs"
exec "$HERE/bin/glm-built" "\$@"
EOF
chmod +x "$HERE/bin/glm-run.new"
mv -f "$HERE/bin/glm-run.new" "$HERE/bin/glm-run"
echo "wrote $HERE/bin/glm-run"; cat "$HERE/bin/glm-run"
